// Regenerates src/generated/nuclo-stats.ts from packages/nuclo-core and packages/nuclo-router
// (package versions + gzipped size of each dist bundle) and rewrites every `<!-- size:KEY -->…<!-- /size -->`
// span in the markdown docs. Run via `bun run update:stats`.
import { brotliCompressSync } from "node:zlib";
import { join, resolve } from "node:path";

const docsDir = resolve(import.meta.dir, "..");
const rootDir = resolve(docsDir, "..");
const coreDir = join(rootDir, "packages", "nuclo-core");
const routerDir = join(rootDir, "packages", "nuclo-router");
const outFile = join(docsDir, "src", "generated", "nuclo-stats.ts");

// Markdown files carrying `<!-- size:core-gzip -->…<!-- /size -->` spans.
const markdownFiles = [
  join(rootDir, "README.md"),
  join(coreDir, "README.md"),
  join(routerDir, "README.md"),
];

const pkg = await Bun.file(join(coreDir, "package.json")).json();
const version: string = pkg.version;
const routerVersion: string = (await Bun.file(join(routerDir, "package.json")).json()).version;

async function bundleBytes(path: string, buildHint: string) {
  const file = Bun.file(path);
  if (!(await file.exists())) {
    console.error(`${path} not found - run \`${buildHint}\` first.`);
    process.exit(1);
  }
  return new Uint8Array(await file.arrayBuffer());
}

const kb = (bytes: number) => (bytes / 1000).toFixed(1);
const core = await bundleBytes(join(coreDir, "dist", "nuclo.mjs"), "bun run build` in packages/nuclo-core");
const router = await bundleBytes(join(routerDir, "dist", "nuclo-router.mjs"), "bun run build` in packages/nuclo-router");

const gzipKb = kb(Bun.gzipSync(core, { level: 9 }).byteLength);
const sizes: Record<string, string> = {
  "core-gzip": gzipKb,
  "router-gzip": kb(Bun.gzipSync(router, { level: 9 }).byteLength),
  "router-brotli": kb(brotliCompressSync(router).byteLength),
};

async function writeIfChanged(path: string, content: string) {
  const file = Bun.file(path);
  if ((await file.exists()) && (await file.text()) === content) return false;
  await Bun.write(path, content);
  return true;
}

const content = `// Auto-generated by scripts/update-doc-stats.ts - do not edit by hand.
export const NUCLO_VERSION = "${version}";
export const NUCLO_GZIP_KB = "${gzipKb}";
export const NUCLO_ROUTER_VERSION = "${routerVersion}";
export const NUCLO_ROUTER_GZIP_KB = "${sizes["router-gzip"]}";
`;
console.log(`nuclo-stats.ts ${(await writeIfChanged(outFile, content)) ? "updated" : "up to date"} (v${version}, ${gzipKb} KB gzipped)`);

for (const path of markdownFiles) {
  const md = await Bun.file(path).text();
  const next = md.replace(/(<!-- size:([\w-]+) -->)[^<]*(<!-- \/size -->)/g, (_, open, key, close) => {
    if (!(key in sizes)) throw new Error(`${path}: unknown size key "${key}"`);
    return open + sizes[key] + close;
  });
  console.log(`${path.slice(rootDir.length + 1)} ${(await writeIfChanged(path, next)) ? "updated" : "up to date"}`);
}
