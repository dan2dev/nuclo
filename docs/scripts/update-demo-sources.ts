// Regenerates src/generated/*-demo-sources.ts from the demo apps' source files,
// so the examples page shows their real, running source. Run via `bun run update:demos`.
import { join, resolve } from "node:path";

const docsDir = resolve(import.meta.dir, "..");
const demosDir = join(docsDir, "src", "demos");
const generatedDir = join(docsDir, "src", "generated");

const ROUTER_FILES = [
  "routes.ts", "app.ts", "main.ts",
  "pages/Home.ts", "pages/Docs.ts", "pages/Topic.ts", "pages/Post.ts",
  "pages/Shop.ts", "pages/Section.ts", "sidebar.ts",
  "pages/Order.ts", "pages/NewCustomer.ts", "pages/NotFound.ts",
];

// The "app" examples under src/demos/apps: one tab per file, in this order.
const APP_FILES: Record<string, string[]> = {
  "page-builder": ["app.ts", "model.ts", "styles.ts"],
  sorting: ["app.ts", "algorithms.ts", "styles.ts"],
  kanban: ["app.ts", "board.ts", "styles.ts"],
  three: ["app.ts", "scene.ts", "styles.ts"],
  "infinite-scroll": ["app.ts", "api.ts", "styles.ts"],
  desktop: ["app.ts", "windows.ts", "programs.ts", "filesystem.ts", "board.ts", "kanban.ts", "calendar.ts", "money.ts", "db.ts", "charts.ts", "finance.ts", "icons.ts", "context-menu.ts", "styles.ts"],
  "data-grid": ["app.ts", "data.ts", "styles.ts"],
  chat: ["app.ts", "server.ts", "styles.ts"],
  dashboard: ["app.ts", "feeds.ts", "styles.ts"],
  "pixel-editor": ["app.ts", "history.ts", "styles.ts"],
  snake: ["app.ts", "game.ts", "styles.ts"],
  sequencer: ["app.ts", "audio.ts", "styles.ts"],
  i18n: ["app.ts", "messages.ts", "styles.ts"],
  "theme-editor": ["app.ts", "theme.ts", "gallery.ts", "styles.ts"],
  "node-graph": ["app.ts", "engine.ts", "graph.ts", "styles.ts"],
};

const read = async (dir: string, file: string) => (await Bun.file(join(dir, file)).text()).trim();

async function writeIfChanged(name: string, content: string, count: number) {
  const outFile = join(generatedDir, name);
  const current = (await Bun.file(outFile).exists()) ? await Bun.file(outFile).text() : "";
  if (current !== content) await Bun.write(outFile, content);
  console.log(`${name} ${current !== content ? "updated" : "up to date"} (${count} files)`);
}

const routerEntries: string[] = [];
for (const file of ROUTER_FILES) {
  routerEntries.push(`  ${JSON.stringify(file)}: ${JSON.stringify(await read(join(demosDir, "router"), file))},`);
}
await writeIfChanged("router-demo-sources.ts", `// Auto-generated by scripts/update-demo-sources.ts - do not edit by hand.
// The source files of src/demos/router, the app the routing examples run.
export const ROUTER_DEMO_SOURCES: Record<string, string> = {
${routerEntries.join("\n")}
};
`, ROUTER_FILES.length);

const appEntries: string[] = [];
let appCount = 0;
for (const [app, files] of Object.entries(APP_FILES)) {
  const list: string[] = [];
  for (const file of files) {
    list.push(`    { name: ${JSON.stringify(file)}, code: ${JSON.stringify(await read(join(demosDir, "apps", app), file))} },`);
    appCount++;
  }
  appEntries.push(`  ${JSON.stringify(app)}: [\n${list.join("\n")}\n  ],`);
}
await writeIfChanged("app-demo-sources.ts", `// Auto-generated by scripts/update-demo-sources.ts - do not edit by hand.
// The source files of src/demos/apps/*, the apps the "Apps" examples run.
export const APP_DEMO_SOURCES: Record<string, { name: string; code: string }[]> = {
${appEntries.join("\n")}
};
`, appCount);

// ── StackBlitz projects (src/stackblitz.ts, src/pages/examples/stackblitz.ts) ──────────────────────
// The hero's examples ship as they are, so the project runs exactly what the hero runs. Each one is cut out of
// pages/home/examples.ts (or playground.ts) with the pieces it uses: the shared styles, the helpers, the keyframes.
// Only the docs' code-view panes are left out.
const srcDir = join(docsDir, "src");
const lines = async (file: string) => (await Bun.file(join(srcDir, file)).text()).split("\n");
const at = (ls: string[], re: RegExp, from = 0) => {
  const i = ls.findIndex((l, n) => n >= from && re.test(l));
  if (i < 0) throw new Error(`update-demo-sources: ${re} not found`);
  return i;
};
const upTo = (ls: string[], from: RegExp, to: RegExp) => ls.slice(at(ls, from), at(ls, to, at(ls, from) + 1)).join("\n").trimEnd();

const heroLines = await lines("pages/home/examples.ts");
const stylesLines = await lines("styles.ts");
const sharedStyles = upTo(heroLines, /^const MONO/, /^\/\*\* A static, highlighted code pane/)
  .replace(/^const (MONO|reduced|focus|noSelect)\b/gm, "export const $1");
const helperBlock = upTo(heroLines, /^export const motion/, /^\/\/ ── Fireworks/).replace(/^const (clamp|pick)\b/gm, "export const $1");
const heroType = upTo(heroLines, /^type Child/, /^const MONO/).replace("code: Child; ", "");

const colorsBlock = upTo(stylesLines, /^export const colors = \{/, /^export \{ registerGlobalStyles/);
const createCssBlock = upTo(stylesLines, /^export const \{ css, cx \} = createCss/, /^\/\/ Shared style helpers/);

const heroShared: Record<string, string> = {
  "src/styles/example.ts": `import { createCss } from "nuclo";
import { animations } from "./animations.ts";

${colorsBlock}

${createCssBlock}

${sharedStyles}

// The page the example sits in
export const page = css({ display: "grid", placeItems: "center", minHeight: "100vh", padding: "24px" });
export const frame = css({ width: "min(720px, 100%)", borderRadius: "16px", border: \`1px solid \${colors.border}\` });
`,
  "src/helpers.ts": `${heroType}\n\n${helperBlock}\n`,
  "src/styles/animations.ts": await Bun.file(join(srcDir, "styles", "animations.ts")).text(),
  "src/logo.ts": await Bun.file(join(srcDir, "components", "brand-geometry.ts")).text(),
};

const sections: Record<string, string> = {};
const marks = heroLines.map((l, n) => (l.startsWith("// ── ") ? n : -1)).filter((n) => n >= 0);
marks.forEach((start, k) => {
  const name = heroLines[start].slice(6).split(":")[0];
  sections[name] = heroLines.slice(start, marks[k + 1] ?? heroLines.length).join("\n").trimEnd();
});
const playLines = await lines("pages/home/playground.ts");
const importEnd = playLines.reduce((last, l, n) => (l.startsWith("import ") ? n : last), 0);
let paint = playLines.slice(importEnd + 1).join("\n").trimStart();
paint = paint.replace(/\n  \/\/ The same thing, as the code someone would write[\s\S]*?\n(?=  return \{)/, "\n").replace(/\n\s*code: Code\(\),/, "");
sections.Paint = paint;
const waves = sections.Waves.match(/^const wv = \{[\s\S]*?^\};/m)?.[0] ?? "";

const HERO = ["Paint", "Draw", "Fireworks", "Waves", "Sort", "Chase", "Reflex", "Warp", "Life"];
const fromStyles = ["colors", "css", "cx", "ex", "EASE", "MONO", "reduced", "focus", "noSelect"];
const fromHelpers = ["clamp", "frames", "motion", "pick", "svgPoint"];
const heroEntries: string[] = [];
for (const name of HERO) {
  let body = sections[name].replace(/\n[ \t]*code: StaticCode\(`(?:\\[\s\S]|[^`\\])*`\),/g, "");
  if (/\bwv\./.test(body) && !/^const wv\b/m.test(body)) body = `${waves}\n\n${body}`;
  const uses = (id: string) => new RegExp(`\\b${id}\\b`).test(body) && !new RegExp(`^(export )?const ${id}\\b`, "m").test(body);
  const imports = [
    `import { ${fromStyles.filter(uses).join(", ")} } from "./styles/example.ts";`,
    uses("animations") || /\banimations\./.test(body) ? `import { animations } from "./styles/animations.ts";` : "",
    `import { ${[...fromHelpers.filter(uses), "type HeroExample"].join(", ")} } from "./helpers.ts";`,
    /\bPOINTS\b|\bicon\./.test(body) ? `import { icon, pathD, N as POINTS, STROKE } from "./logo.ts";` : "",
  ].filter(Boolean);
  heroEntries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(`${imports.join("\n")}\n\n${body}\n`)},`);
}
await writeIfChanged("hero-projects.ts", `// Auto-generated by scripts/update-demo-sources.ts - do not edit by hand.
// The hero examples as StackBlitz projects (src/stackblitz.ts): the files they share, and each example's own.
export const HERO_SHARED: Record<string, string> = ${JSON.stringify(heroShared, null, 2)};

/** Each hero example's src/example.ts. */
export const HERO_EXAMPLES: Record<string, string> = {
${heroEntries.join("\n")}
};
`, HERO.length + 4);

// ── The examples page: the docs' theme, and the router demo app ─────────────────────────────────────
const globalSrc = (await Bun.file(join(srcDir, "styles", "global.ts")).text()).split("\n");
const first = globalSrc.findIndex((l) => l.includes('globalStyle("[data-theme=')), last = globalSrc.findIndex((l) => l.includes('globalStyle("svg"'));
if (first < 0 || last < first) throw new Error("styles/global.ts: the base styles moved");
const base = globalSrc.slice(first, last + 1).filter((l) => l.trim().startsWith("globalStyle(") || l.trim().startsWith("//")).map((l) => l.trim());
const selection = globalSrc.find((l) => l.includes('globalStyle("::selection"'))!.trim();
const exampleTheme = `import "nuclo";

// The docs' base styles, as the docs set them. The theme follows the system, like the docs' own.
document.documentElement.setAttribute("data-theme", matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");

${[...base, selection].join("\n")}
`;
await writeIfChanged("example-theme.ts", `// Auto-generated by scripts/update-demo-sources.ts - do not edit by hand.
// src/styles/theme.ts of every StackBlitz project: the docs' base styles, as a Nuclo globalStyle().
export const EXAMPLE_THEME = ${JSON.stringify(exampleTheme)};
`, 1);

const routerFiles = [...new Bun.Glob("**/*.ts").scanSync(join(demosDir, "router"))].sort();
// On the docs the app lives under /demos/router; on StackBlitz it is served from the root
const fromRoot = (code: string) => code.replaceAll('base: "/demos/router", // the app lives under this prefix', 'base: "", // served from the root').replaceAll('{ base: "/demos/router" }', '{ base: "" }');
const routerEntries2: string[] = [];
for (const file of routerFiles) routerEntries2.push(`  ${JSON.stringify(file)}: ${JSON.stringify(fromRoot(await Bun.file(join(demosDir, "router", file)).text()))},`);
await writeIfChanged("example-projects.ts", `// Auto-generated by scripts/update-demo-sources.ts - do not edit by hand.
// The router demo app (src/demos/router), every file, as it runs on its own: a routing example's StackBlitz project.
export const ROUTER_PROJECT: Record<string, string> = {
${routerEntries2.join("\n")}
};
`, routerFiles.length);
