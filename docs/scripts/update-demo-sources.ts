// Regenerates src/generated/router-demo-sources.ts from src/demos/router so the
// examples page shows the demo app's real, running source. Run via `bun run update:demos`.
import { join, resolve } from "node:path";

const docsDir = resolve(import.meta.dir, "..");
const demoDir = join(docsDir, "src", "demos", "router");
const outFile = join(docsDir, "src", "generated", "router-demo-sources.ts");

const files = [
  "routes.ts", "app.ts", "main.ts",
  "pages/Home.ts", "pages/Docs.ts", "pages/Topic.ts", "pages/Post.ts",
  "pages/Order.ts", "pages/NewCustomer.ts", "pages/NotFound.ts",
];

const entries: string[] = [];
for (const file of files) {
  const src = (await Bun.file(join(demoDir, file)).text()).trim();
  entries.push(`  ${JSON.stringify(file)}: ${JSON.stringify(src)},`);
}

const content = `// Auto-generated by scripts/update-demo-sources.ts - do not edit by hand.
// The source files of src/demos/router, the app the routing examples run.
export const ROUTER_DEMO_SOURCES: Record<string, string> = {
${entries.join("\n")}
};
`;
const current = (await Bun.file(outFile).exists()) ? await Bun.file(outFile).text() : "";
if (current !== content) await Bun.write(outFile, content);
console.log(`router-demo-sources.ts ${current !== content ? "updated" : "up to date"} (${files.length} files)`);
