// Builds the app for one platform: `bun scripts/build.ts <web|android|linux|linux-gpui|ios|macos>`.
// Each platform gets the .ns sources compiled by nns, its renderer (native/<platform>), the Nuclo Script
// runtime of its language (runtime/nns_*), and its own nuclo runtime (runtime/<platform>).
import { $ } from "bun";
import { readdirSync } from "node:fs";

const target = process.argv[2] ?? "";
const NNS = ["bun", `${import.meta.dir}/../../../../nns-poc/vscode-extension/dist/nns.js`];
const root = `${import.meta.dir}/..`;
process.chdir(root);

const sources = readdirSync("src").filter((f) => f.endsWith(".ns")).map((f) => `src/${f}`);
const modules = sources.map((f) => f.slice(4, -3).toLowerCase());
const nns = (t: string, outDir: string, rootDir = "src", files = sources) =>
  $`${NNS} build --target ${t} --rootDir ${rootDir} --outDir ${outDir} --runtime runtime/nns_rt.rs ${files}`.quiet();

async function rust(platform: "linux" | "linux-gpui") {
  const out = `build/${platform}`;
  await $`rm -rf ${out}/src && mkdir -p ${out}/src`;
  await nns("rs", `${out}/src`);
  const backend = platform === "linux" ? ["runtime/rust-gtk/gtk_backend.rs"] : ["runtime/rust-gpui/gpui_backend.rs", "runtime/rust-gpui/gpui_field.rs"];
  await $`cp native/rust/native.rs runtime/nns_rt.rs ${backend} ${out}/src/ && cp -r runtime/rust/nuclo ${out}/src/ && cp native/${platform}/Cargo.toml ${out}/ && cp native/${platform}/controls.rs ${out}/src/`;
  const mods = [...modules, "controls", "native", "nns_rt", "nuclo", ...backend.map((f) => f.split("/").pop()!.slice(0, -3))].sort();
  const run = platform === "linux" ? "gtk_backend::run(app::main)" : "gpui_backend::run(app::main)";
  // The mode of the platform's chrome: libadwaita's colour scheme on GTK; GPUI draws the chrome itself.
  const dark =
    platform === "linux"
      ? `pub fn set_dark(dark: bool, accent: &str) {\n  adw::StyleManager::default().set_color_scheme(if dark { adw::ColorScheme::ForceDark } else { adw::ColorScheme::ForceLight });\n  controls::set_accent(accent);\n}\n`
      : `pub fn set_dark(_dark: bool, _accent: &str) {}\n`;
  await Bun.write(
    `${out}/src/main.rs`,
    `// Generated by scripts/build.ts: the crate root of the ${platform} build.\n${mods.map((m) => `mod ${m};`).join("\n")}\n\n` +
      `pub const PLATFORM: &str = "${platform}";\n\n${dark}\nfn main() {\n  ${run};\n}\n`,
  );
  await $`cargo build --offline --release`.cwd(out);
  console.log(`${out}/target/release/nuclo-native-ns${platform === "linux" ? "" : "-gpui"}`);
}

async function web() {
  const out = "build/web";
  // Written over in place: a running dev server keeps watching the same files.
  await $`mkdir -p ${out}/src`;
  await $`cp ${sources} native/web/extern.ts ${out}/src/ && cp native/web/index.html native/web/main.ts ${out}/`;
  await $`${NNS} build --target ts --rootDir ${out}/src --outDir ${out}/out --runtime ${`${root}/runtime/nns_runtime.ts`} ${sources.map((f) => `${out}/src/${f.slice(4)}`)}`.quiet();
}

async function android() {
  const out = `${root}/build/android`;
  await $`rm -rf ${out} && mkdir -p ${out}`;
  await nns("kt", out);
  await $`cp native/android/*.kt runtime/NnsRuntime.kt runtime/android/NucloRuntime.kt runtime/android/NucloJs.kt ${out}/`;
  const host = "hosts/android";
  const jbr = `${process.env.HOME}/.local/share/JetBrains/Toolbox/apps/android-studio/jbr`;
  const env = { ...process.env, JAVA_HOME: process.env.JAVA_HOME ?? jbr, ANDROID_HOME: process.env.ANDROID_HOME ?? `${process.env.HOME}/Android/Sdk` };
  await $`rm -rf app/build/kotlin app/build/intermediates/built_in_kotlinc app/build/tmp/kotlin-classes`.cwd(host);
  const release = process.argv.includes("--release");
  await $`./gradlew ${release ? "assembleRelease" : "assembleDebug"} --offline -PnucloSources=${out} -PnucloAppLabel=nuclo`.cwd(host).env(env);
  console.log(`${host}/app/build/outputs/apk/${release ? "release/app-release" : "debug/app-debug"}.apk`);
}

/**
 * iOS and macOS share the Swift sources: build/<platform>/app is the generated code, native/ios, and the Nuclo
 * Script runtime (the module NucloApp); build/<platform>/nuclo is the runtime of nuclo (the module Nuclo), on
 * UIKit, or on AppKit through runtime/macos/UIKitShim.swift. scripts/<platform>.sh compiles them on a Mac.
 */
async function swift(platform: "ios" | "macos") {
  const out = `build/${platform}`;
  await $`rm -rf ${out} && mkdir -p ${out}/app ${out}/nuclo`;
  await $`${NNS} build --target swift --rootDir src --outDir ${out}/app ${sources}`.quiet();
  await $`cp native/ios/*.swift runtime/NNSRuntime.swift ${out}/app/ && cp runtime/ios/NucloRuntime.swift ${out}/nuclo/`;
  if (platform === "macos") await $`cp runtime/macos/UIKitShim.swift ${out}/nuclo/`;
  await Bun.write(`${out}/app/Platform.swift`, `// Generated by scripts/build.ts.\nlet PLATFORM = "${platform}"\n`);
  console.log(`${out}: build and run on a Mac with scripts/${platform}.sh`);
}

const builds: Record<string, () => Promise<void>> = {
  web,
  android,
  linux: () => rust("linux"),
  "linux-gpui": () => rust("linux-gpui"),
  ios: () => swift("ios"),
  macos: () => swift("macos"),
};
if (!builds[target]) throw new Error(`usage: bun scripts/build.ts ${Object.keys(builds).join(" | ")}`);
await builds[target]();
